// 위치 확인을 쓸 것인가 — 한 곳에서만 답한다.
//
// 2026-09-14 사장님: "위치기반 주문제한 해제를 누르고, 밑에 설정저장을 누르면
// 저장되었습니다. 문구 표시됨. 그런데, 새로고침을 하거나 다른 곳에 다녀오면,
// 도로 제자리로 돌아가서 위치기반주문제한이 사용된다고 체크박스에 체크돼
// 있어요."
//
// 저장은 되고 있었다. 읽는 쪽이 그것을 못 알아봤다.
//
// 관리자 화면은 체크박스라 참/거짓을 보낸다. 그런데 설정 저장 코드가 받은
// 값을 전부 String() 으로 감쌌다 — 다른 칸이 전부 글자였기 때문이다. 그래서
// 거짓(false)이 글자 "false" 로 저장됐다. 그 다음 읽는 쪽은 하나같이
//
//     store.settings.location_check_enabled !== false
//
// 로 물었고, 글자 "false" 는 참/거짓 false 가 아니므로 전부 「켜짐」으로
// 답했다.
//
// 체크박스가 되돌아가는 것만 문제가 아니었다. 같은 비교를 주문 쪽에서도
// 쓰고 있었으므로(src/routes/orders.js), 껐다고 믿은 위치 제한이 실제로는
// 그대로 살아 있었다. 손님 폰도 위치를 계속 물었다. 화면이 되돌아가는 것은
// 그중 눈에 보이는 부분일 뿐이었다.
//
// 그래서 묻는 자리를 하나로 모은다. 이미 저장돼 있는 글자 "false" 도 여기서
// 제대로 읽으므로 따로 손볼 데이터가 없다.
//
// 저장된 적이 없으면 켜진 것으로 본다 — 지금까지 쓰던 대로다. 끄는 것은
// 사장님이 직접 끈 경우뿐이어야 한다.
const OFF = new Set([false, 0, "false", "0", "off", "no", ""]);

/** 지금 위치 확인이 켜져 있는가. */
function isOn(settings) {
  const v = (settings || {}).location_check_enabled;
  if (v == null) return true;
  return !OFF.has(typeof v === "string" ? v.trim().toLowerCase() : v);
}

module.exports = { isOn };
